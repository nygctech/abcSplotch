import os
import glob
import numpy as np
from tqdm import tqdm
from pathlib import Path
from scipy.stats import nbinom

from splotch.utils import read_rdump, to_rdump

def stochastic_round(x):
    x = np.asarray(x)
    floor = np.floor(x)
    frac = x - floor
    return (floor + (np.random.random(x.shape) < frac)).astype(int)

# Obtain (n,p) parameterization of NB distribution from mean, overdispersion
def np_from_mu_alpha(mu, alpha):
    n = 1.0 / alpha
    p = 1.0 / (1.0 + alpha * mu)
    return n, p

def simdata(rdat, n_per_cond, fold_change, query_cond=None, sim_mu=None, sim_alpha=None, 
            spatial=False, test_type=None):
    '''
    Parameters:
    ----------
    rdat: dict
        splotch input file read in by read_rdump
    n_per_cond: int
        number of arrays to simulate per condition
    fold_change: float
        fold change in expression to simulate between query and test group
    query_cond: int or None
        index of (level 1) condition to use as the "query";
        simulated data will be generated based on these to use as "test".
        if None, both query and test will draw from pool of all tissues
    sim_mu: float or None
        mean of simulated NB counts data. If None, existing counts are used
        for query data (and query data generated by deterministic scaling)
    sim_alpha: float or None
        overdispersion of simulated NB data. See sim_mu for None behavior
    spatial: bool
        whether to include spatial information in simulated data
    test_type: int or None
        index of cell type in which to induce expression change. 
        If None, global change across all types

    Returns:
    -------
    rdat_sim: dict
        dictionary containing simulated data
    '''

    def _tissue_spot_inds(t_ind):
        csum = np.cumsum(rdat['N_spots'])
        if t_ind==0:
            return np.arange(0, csum[0])
        else:
            return np.arange(csum[t_ind-1], csum[t_ind])

    def _reindex_tissue_regions(t_ind):
        spot_inds = _tissue_spot_inds(t_ind)

        region_list = rdat['region_list'][spot_inds]
        W_sparse = np.array([edge for edge in rdat['W_sparse'] if (edge[0] in region_list and edge[1] in region_list)])

        # scale between 1 and R
        rmin = np.min(region_list)-1
        region_list = region_list - rmin
        W_sparse = W_sparse - rmin

        return region_list, W_sparse

    if query_cond is not None:
        pool = np.where(rdat['tissue_mapping']==query_cond)[0]
    else:
        pool = np.arange(rdat['N_tissues'])

    # Select "query" samples
    query = np.random.choice(pool, n_per_cond, replace=True)

    # track cumulative number of regions (if using spatial information)
    if spatial:
        cum_reg = 0
        query_W_sparse, test_W_sparse = [],[]
        query_region_list, test_region_list = [],[]

    query_counts, query_D, query_size_factors, query_N_spots = [],[],[],[]
    for q in query:
        q_inds = _tissue_spot_inds(q)
        query_D.append(rdat['D'][q_inds])
        query_N_spots.append(len(q_inds))
        
        query_s = rdat['size_factors'][q_inds]
        query_size_factors.append(query_s)

        if sim_mu is not None and sim_alpha is not None:
            n_param, p_param = np_from_mu_alpha(sim_mu * query_s, sim_alpha)
            simcounts = nbinom.rvs(n_param, p_param, size=len(q_inds))
        else:
            simcounts = rdat['counts'][q_inds]
        query_counts.append(simcounts)

        if spatial:
            region_list, W_sparse = _reindex_tissue_regions(q)
            cum_reg += max(region_list)
            query_region_list.append(region_list + cum_reg)
            query_W_sparse.append(W_sparse + cum_reg)

    # Create "test" samples
    test = np.random.choice(pool, n_per_cond, replace=True)

    test_counts, test_D, test_size_factors, test_N_spots = [],[],[],[]
    for t in test:
        t_inds = _tissue_spot_inds(t)
        test_D.append(rdat['D'][t_inds])
        test_N_spots.append(len(t_inds))
        
        test_s = rdat['size_factors'][t_inds]
        test_size_factors.append(test_s)

        if sim_mu is not None and sim_alpha is not None:
            if test_type is None:
                n_param, p_param = np_from_mu_alpha(sim_mu * test_s * fold_change, sim_alpha)
                simcounts = nbinom.rvs(n_param, p_param, size=len(t_inds))
            else:
                n,p1 = np_from_mu_alpha(sim_mu * test_s * fold_change, sim_alpha)
                _,p2 = np_from_mu_alpha(sim_mu * test_s, sim_alpha)

                D = rdat['D'][t_inds]
                simcounts = np.zeros_like(D)
                simcounts[D==test_type] = nbinom.rvs(n, p1[D==test_type])
                simcounts[D!=test_type] = nbinom.rvs(n, p2[D!=test_type])
        else:
            simcounts = rdat['counts'][t_inds] * fold_change
            if test_type is not None:
                raise NotImplementedError
                
        test_counts.append(simcounts)

        if spatial:
            region_list, W_sparse = _reindex_tissue_regions(t)
            cum_reg += max(region_list)
            test_region_list.append(region_list + cum_reg)
            test_W_sparse.append(W_sparse + cum_reg)

    rdat_out = {
        'N_spots': query_N_spots + test_N_spots,
        'N_tissues': 2 * n_per_cond,
        'N_covariates': rdat['N_covariates'],
        'tissue_mapping': [1]*n_per_cond + [2]*n_per_cond,
        'N_levels': 1,
        'car':int(spatial),
        'N_level_1':2,
        'size_factors': np.concatenate(query_size_factors + test_size_factors),
        'D': np.concatenate(query_D + test_D),
        'counts': stochastic_round(np.concatenate(query_counts + test_counts))
    }
    if spatial:
        rdat_out['W_sparse'] = np.concatenate(query_W_sparse + test_W_sparse)
        rdat_out['region_list'] = np.concatenate(query_region_list + test_region_list)
        
    return rdat_out
    